// Generates src/shared/styles/fluent-tokens.css from Fluent UI v9 themes.
//   node scripts/build-theme.mjs
//
// Every Fluent token (--colorNeutralBackground1, --borderRadiusMedium, …) is
// defined once on :root, dark by default and light under
// prefers-color-scheme: light. Fluent components and our own Astro CSS read the
// same variables, so there is one design system and no theme flash: the
// FluentProvider gets no theme object of its own.

import { writeFileSync } from "node:fs";
import { createDarkTheme, createLightTheme } from "@fluentui/react-components";

// --- Champagne brand ramp (16 steps, 10 = darkest, 160 = lightest) ---------

function oklchToHex(L, C, h) {
  const a = C * Math.cos((h * Math.PI) / 180);
  const b = C * Math.sin((h * Math.PI) / 180);
  const l_ = L + 0.3963377774 * a + 0.2158037573 * b;
  const m_ = L - 0.1055613458 * a - 0.0638541728 * b;
  const s_ = L - 0.0894841775 * a - 1.291485548 * b;
  const [l, m, s] = [l_ ** 3, m_ ** 3, s_ ** 3];
  const lin = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ];
  return (
    "#" +
    lin
      .map((c) => {
        const v = c <= 0.0031308 ? 12.92 * c : 1.055 * c ** (1 / 2.4) - 0.055;
        return Math.round(Math.min(1, Math.max(0, v)) * 255)
          .toString(16)
          .padStart(2, "0");
      })
      .join("")
  );
}

const brand = {};
for (let i = 0; i < 16; i++) {
  const t = i / 15;
  const L = 0.16 + t * 0.8; // 0.16 … 0.96
  const C = 0.02 + Math.sin(t * Math.PI) * 0.075; // most chroma mid-ramp
  const h = 70 + t * 15; // bronze → champagne
  brand[(i + 1) * 10] = oklchToHex(L, C, h);
}

const FONT =
  '"Segoe UI Variable Text", "Segoe UI", "Inter Variable", -apple-system, BlinkMacSystemFont, Roboto, sans-serif';

const light = { ...createLightTheme(brand), fontFamilyBase: FONT };
const dark = { ...createDarkTheme(brand), fontFamilyBase: FONT };

// Champagne is light: on brand fills use dark ink in dark mode.
Object.assign(dark, {
  colorBrandBackground: brand[120],
  colorBrandBackgroundHover: brand[130],
  colorBrandBackgroundPressed: brand[110],
  colorBrandBackgroundSelected: brand[120],
  colorCompoundBrandBackground: brand[120],
  colorCompoundBrandBackgroundHover: brand[130],
  colorCompoundBrandBackgroundPressed: brand[110],
  colorNeutralForegroundOnBrand: "#1a1610",
  colorBrandForeground1: brand[130],
  colorBrandForeground2: brand[140],
  colorBrandForegroundLink: brand[130],
  colorBrandForegroundLinkHover: brand[140],
  colorCompoundBrandStroke: brand[120],
  colorBrandStroke1: brand[120],
});
// Light mode: deep bronze for contrast on white.
Object.assign(light, {
  colorBrandBackground: brand[60],
  colorBrandBackgroundHover: brand[50],
  colorBrandBackgroundPressed: brand[40],
  colorCompoundBrandBackground: brand[60],
  colorBrandForeground1: brand[60],
  colorBrandForegroundLink: brand[60],
  colorBrandForegroundLinkHover: brand[50],
});

const block = (theme) =>
  Object.entries(theme)
    .map(([k, v]) => `  --${k}: ${v};`)
    .join("\n");

const css = `/* Generated by scripts/build-theme.mjs — do not edit by hand. */
/* Fluent UI v9 tokens: dark (default) and light, champagne brand ramp. */

:root {
  color-scheme: dark light;
${block(dark)}
}

@media (prefers-color-scheme: light) {
  :root {
${block(light).replace(/^ {2}/gm, "    ")}
  }
}
`;

writeFileSync(
  new URL("../src/shared/styles/fluent-tokens.css", import.meta.url),
  css,
);
console.log("brand ramp:", Object.values(brand).join(" "));
